const TABLES = { en, pt, es }

export function makeT (lang) {
  const table = TABLES[lang] || en
  return function t (key, params) {
    let s = table[key] ?? en[key]
    if (s === undefined) return key
    if (Array.isArray(s)) return s.map(x => fill(x, params))
    return fill(s, params)
  }
}

function fill (s, params) {
  if (!params) return s
  return String(s).replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined && params[k] !== null ? String(params[k]) : m))
}

// Locale for dates and numbers.
export const LOCALES = { en: 'en-US', pt: 'pt-BR', es: 'es-ES' }

// The browser's language on first launch, if the Center speaks it.
export function defaultLang () {
  try {
    const l = (navigator.language || 'en').slice(0, 2).toLowerCase()
    return TABLES[l] ? l : 'en'
  } catch { return 'en' }
}

